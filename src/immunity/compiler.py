"""Ahead-of-time (AOT) static script compiler for Zsh."""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Sequence

from immunity.models import PluginLock, PluginSpec


def resolve_plugin_root(base_dir: Path, spec: PluginSpec) -> Path:
    """Resolve the effective root directory for a plugin considering subpath."""
    if spec.subpath:
        sub_dir = base_dir / spec.subpath
        if sub_dir.is_dir():
            return sub_dir
    return base_dir


def find_init_script(base_dir: Path, spec: PluginSpec) -> Path | None:
    """Discover the appropriate entry point script according to Zsh standards."""
    root_dir = resolve_plugin_root(base_dir, spec)

    # If the user requested fpath-only or path-only, do not source any script
    if spec.kind in ("fpath", "path"):
        return None

    # 1. Explicit pick / source directive
    if spec.pick:
        candidate = root_dir / spec.pick
        if candidate.is_file():
            return candidate

    plugin_name = spec.name

    # 2. Standard Zsh plugin naming conventions
    standard_candidates = [
        f"{plugin_name}.plugin.zsh",
        f"{plugin_name}.zsh",
        f"{plugin_name}.zsh-theme",
        "init.zsh",
    ]

    for filename in standard_candidates:
        candidate = root_dir / filename
        if candidate.is_file():
            return candidate

    # 3. Fallback discovery for any *.plugin.zsh, *.zsh-theme, or *.zsh
    for pattern in ("*.plugin.zsh", "*.zsh-theme", "*.zsh"):
        matched = sorted(root_dir.glob(pattern))
        if matched:
            return matched[0]

    return None


def find_fpath_directories(base_dir: Path, spec: PluginSpec) -> list[Path]:
    """Find directories containing completions or autoload functions to add to fpath."""
    root_dir = resolve_plugin_root(base_dir, spec)
    fpaths: list[Path] = []

    # Check common completion / autoload folder conventions
    candidate_subdirs = ["autoload", "functions", "completions", "_completion", "src"]
    for subdir_name in candidate_subdirs:
        sub = root_dir / subdir_name
        if sub.is_dir():
            fpaths.append(sub)

    # Check if the root directory contains any completion files (starting with underscore)
    try:
        has_completions = any(
            f.name.startswith("_") and f.is_file() for f in root_dir.iterdir()
        )
    except OSError:
        has_completions = False

    # By default, add root directory to fpath unless already included
    if root_dir not in fpaths:
        fpaths.insert(0, root_dir)

    return fpaths


def find_bin_directories(base_dir: Path, spec: PluginSpec) -> list[Path]:
    """Find binary / executable directories for PATH addition."""
    root_dir = resolve_plugin_root(base_dir, spec)
    bin_dirs: list[Path] = []
    for candidate in ("bin", "bin/exec"):
        sub = root_dir / candidate
        if sub.is_dir():
            bin_dirs.append(sub)
    if spec.kind == "path" and root_dir not in bin_dirs:
        bin_dirs.append(root_dir)
    return bin_dirs


def compile_static_script(
    results: Sequence[tuple[PluginSpec, Path | None, PluginLock | None]],
) -> str:
    """Compile synchronized plugins into a high-performance static Zsh script."""
    timestamp = datetime.now(timezone.utc).isoformat()
    lines = [
        "# -----------------------------------------------------------------------------",
        "# AUTOMATICALLY GENERATED BY IMMUNITY (AOT Zsh Plugin Compiler)",
        f"# Compiled At: {timestamp}",
        "# Do not edit this file directly.",
        "# -----------------------------------------------------------------------------",
        "",
    ]

    # Collect and deduplicate fpaths
    seen_fpaths: set[str] = set()
    fpath_lines: list[str] = []
    for spec, path, _ in results:
        if path is None or not path.is_dir():
            continue
        for fdir in find_fpath_directories(path, spec):
            posix_path = fdir.as_posix()
            if posix_path not in seen_fpaths:
                seen_fpaths.add(posix_path)
                fpath_lines.append(f'fpath=("{posix_path}" $fpath)')

    if fpath_lines:
        lines.append("# --- Completions & Autoload Functions (fpath) ---")
        lines.extend(fpath_lines)
        lines.append("")

    # Collect and deduplicate bin directories for PATH
    seen_paths: set[str] = set()
    path_lines: list[str] = []
    for spec, path, _ in results:
        if path is None or not path.is_dir():
            continue
        for bdir in find_bin_directories(path, spec):
            posix_path = bdir.as_posix()
            if posix_path not in seen_paths:
                seen_paths.add(posix_path)
                path_lines.append(f'path=("{posix_path}" $path)')

    if path_lines:
        lines.append("# --- Executables & Binary Directories (path) ---")
        lines.extend(path_lines)
        lines.append("")

    # Plugin script sourcing
    lines.append("# --- Plugins & Sourced Scripts ---")
    sourced_count = 0
    for spec, path, _ in results:
        if path is None or not path.is_dir():
            continue

        init_script = find_init_script(path, spec)
        if init_script is None:
            continue

        sourced_count += 1
        posix_script = init_script.as_posix()
        lines.append(f"# [{spec.target}]")

        if spec.defer is not None and spec.defer > 0:
            lines.append("if (( $+functions[zsh-defer] )); then")
            lines.append(f'  zsh-defer source "{posix_script}"')
            lines.append("else")
            lines.append(f'  source "{posix_script}"')
            lines.append("fi")
        else:
            lines.append(f'source "{posix_script}"')

        lines.append("")

    lines.append(f"# Total plugins sourced: {sourced_count}")
    return "\n".join(lines) + "\n"


def write_compiled_script(path: Path | str, content: str) -> None:
    """Write compiled static shell content to disk."""
    file_path = Path(path).expanduser().resolve()
    file_path.parent.mkdir(parents=True, exist_ok=True)
    file_path.write_text(content, encoding="utf-8")
