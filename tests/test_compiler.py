"""Tests for static Zsh script compiler and heuristics."""

import tempfile
import unittest
from pathlib import Path

from immunity.compiler import (
    compile_static_script,
    find_bin_directories,
    find_fpath_directories,
    find_init_script,
    write_compiled_script,
)
from immunity.models import PluginLock, PluginSpec


class TestCompiler(unittest.TestCase):
    def test_find_init_script_standard(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            repo_dir = Path(td)
            script = repo_dir / "my-plugin.plugin.zsh"
            script.touch()

            spec = PluginSpec(
                raw="user/my-plugin",
                target="user/my-plugin",
                name="my-plugin",
                url="https://github.com/user/my-plugin.git",
            )
            found = find_init_script(repo_dir, spec)
            self.assertEqual(found, script)

    def test_find_init_script_init_fallback(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            repo_dir = Path(td)
            script = repo_dir / "init.zsh"
            script.touch()

            spec = PluginSpec(
                raw="user/repo",
                target="user/repo",
                name="repo",
                url="https://github.com/user/repo.git",
            )
            found = find_init_script(repo_dir, spec)
            self.assertEqual(found, script)

    def test_find_init_script_explicit_pick(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            repo_dir = Path(td)
            script = repo_dir / "custom.zsh"
            script.touch()

            spec = PluginSpec(
                raw="user/repo pick:custom.zsh",
                target="user/repo",
                name="repo",
                url="https://github.com/user/repo.git",
                pick="custom.zsh",
            )
            found = find_init_script(repo_dir, spec)
            self.assertEqual(found, script)

    def test_find_fpath_directories(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            repo_dir = Path(td)
            autoload_dir = repo_dir / "autoload"
            autoload_dir.mkdir()

            spec = PluginSpec(
                raw="user/repo",
                target="user/repo",
                name="repo",
                url="https://github.com/user/repo.git",
            )
            fpaths = find_fpath_directories(repo_dir, spec)
            self.assertIn(repo_dir, fpaths)
            self.assertIn(autoload_dir, fpaths)

    def test_compile_static_script_structure(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            repo_dir = Path(td)
            script = repo_dir / "repo.plugin.zsh"
            script.touch()

            spec = PluginSpec(
                raw="user/repo",
                target="user/repo",
                name="repo",
                url="https://github.com/user/repo.git",
            )
            lock = PluginLock(
                name="repo",
                url=spec.url,
                commit="abc1234",
            )

            results = [(spec, repo_dir, lock)]
            compiled = compile_static_script(results)

            self.assertIn("AUTOMATICALLY GENERATED BY IMMUNITY", compiled)
            self.assertIn(f'fpath=("{repo_dir.as_posix()}" $fpath)', compiled)
            self.assertIn(f'source "{script.as_posix()}"', compiled)
            self.assertIn("Total plugins sourced: 1", compiled)

    def test_compile_with_defer(self) -> None:
        with tempfile.TemporaryDirectory() as td:
            repo_dir = Path(td)
            script = repo_dir / "repo.plugin.zsh"
            script.touch()

            spec = PluginSpec(
                raw="user/repo defer:2",
                target="user/repo",
                name="repo",
                url="https://github.com/user/repo.git",
                defer=2,
            )
            results = [(spec, repo_dir, None)]
            compiled = compile_static_script(results)
            self.assertIn("zsh-defer source", compiled)


if __name__ == "__main__":
    unittest.main()
